import os
import sys


def print_usage():
    print(" Usage: python exyz2lmp.py <extxyz_file> <lammps_data_file>")
    print("")
    print(" Arguments:")
    print("   extxyz_file       Input extxyz file")
    print("   lammps_data_file  Output LAMMPS data file")
    print("")
    print(" Output:")
    print("   <lammps_data_file>")
    print("")
    print(" Example: python exyz2lmp.py model.xyz data.lammps")
    print("")


def convert_extxyz_to_lammps_data(extxyz_file, lammps_data_file):
    from ase.io import read

    # Read the EXTXYZ file
    atoms = read(extxyz_file, format='extxyz')

    # The box lines below assume the LAMMPS orientation (a along x, b in the xy
    # plane), i.e. a lower-triangular cell. Rotate any other cell together with
    # its atoms; a cell already in that form is written unchanged.
    import numpy as np
    det = np.linalg.det(atoms.cell)
    if abs(det) < 1e-8:
        print(" Error: LAMMPS requires a non-singular 3D cell.")
        sys.exit(1)
    if det < 0:
        # Swapping a and b only relabels the lattice vectors: the same periodic
        # structure, now described by a right-handed cell as LAMMPS requires.
        atoms.set_cell(atoms.cell[[1, 0, 2]], scale_atoms=False)
        atoms.set_pbc(atoms.pbc[[1, 0, 2]])
        print(" Note: the left-handed cell was made right-handed by swapping the a and b vectors.")
    if np.abs(np.triu(np.asarray(atoms.cell), k=1)).max() > 1e-8 or np.any(np.diag(atoms.cell) <= 0):
        rotated_cell, rotation = atoms.cell.standard_form()
        atoms.set_positions(atoms.positions @ rotation.T, apply_constraint=False)
        atoms.set_cell(rotated_cell, scale_atoms=False)
        print(" Note: the cell was rotated to the LAMMPS orientation (a along x, b in the xy plane).")
    
    # Get element symbols and masses
    symbols = atoms.get_chemical_symbols()
    masses = atoms.get_masses()
    unique_symbols = sorted(set(symbols))  # Sort to ensure consistent ordering

    # Map each unique symbol to an atom type number starting from 1
    symbol_to_type = {symbol: i + 1 for i, symbol in enumerate(unique_symbols)}
    
    # Create the LAMMPS data file
    with open(lammps_data_file, 'w') as f:
        f.write("Generated by GPUMDkit\n\n")
        
        # Write the number of atoms and atom types
        f.write(f"{len(atoms)} atoms\n")
        f.write(f"{len(unique_symbols)} atom types\n\n")
        
        # Write the box dimensions
        cell = atoms.get_cell()
        f.write(f"0.0 {atoms.cell[0][0]} xlo xhi\n")
        f.write(f"0.0 {atoms.cell[1][1]} ylo yhi\n")
        f.write(f"0.0 {atoms.cell[2][2]} zlo zhi\n")
        f.write(f"{cell[1][0]} {cell[2][0]} {cell[2][1]} xy xz yz\n\n")
        
        # Write the masses
        f.write("Masses\n\n")
        for symbol in unique_symbols:
            atom_type = symbol_to_type[symbol]
            mass = masses[symbols.index(symbol)]
            f.write(f"{atom_type} {mass}\n")
        f.write("\n")
        
        # Write the atomic coordinates
        f.write("Atoms\n\n")
        for i, atom in enumerate(atoms):
            atom_id = i + 1
            atom_type = symbol_to_type[atom.symbol]
            x, y, z = atom.position
            f.write(f"{atom_id} {atom_type} {x} {y} {z}\n")

if __name__ == '__main__':
    args = sys.argv[1:]
    if len(args) != 2 or args[0] in ("-h", "--help"):
        print_usage()
        sys.exit(0 if args and args[0] in ("-h", "--help") else 1)
    
    extxyz_file = args[0]
    lammps_data_file = args[1]
    if not os.path.isfile(extxyz_file):
        print(f" Error: file '{extxyz_file}' does not exist.")
        sys.exit(1)

    convert_extxyz_to_lammps_data(extxyz_file, lammps_data_file)
